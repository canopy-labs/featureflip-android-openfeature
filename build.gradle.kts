// The provider reports its version in the wrapper token. publish workflows sed the
// `version` above from the release tag, so generating PROVIDER_VERSION from it keeps
// the two in step instead of duplicating it in source, where it would drift (#2141).
val generateProviderVersion by tasks.registering {
    val providerVersion = project.version.toString()
    val outDir = layout.buildDirectory.dir("generated/providerVersion")
    inputs.property("version", providerVersion)
    outputs.dir(outDir)
    doLast {
        val file = outDir.get().file("dev/featureflip/android/openfeature/ProviderVersion.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "// Generated by build.gradle.kts from `version` (#2141). Do not edit.\n" +
                "package dev.featureflip.android.openfeature\n\n" +
                "internal const val PROVIDER_VERSION = \"$providerVersion\"\n",
        )
    }
}

